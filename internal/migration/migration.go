// Package migration 启动期数据库结构保障：
// 以既有 PostgreSQL Schema（V1 + P1-07 迁移后的形态）为基准做幂等补齐，
// 不改动既有表结构，保证与 Java 版共存同一数据库。
package migration

import (
	"context"
	"fmt"
	"log/slog"

	"gorm.io/gorm"
)

// statements 幂等 DDL（仅 CREATE IF NOT EXISTS 语义，避免破坏既有数据）。
var statements = []string{
	`CREATE EXTENSION IF NOT EXISTS vector WITH SCHEMA public`,
	`CREATE EXTENSION IF NOT EXISTS hstore WITH SCHEMA public`,
	`CREATE EXTENSION IF NOT EXISTS "uuid-ossp" WITH SCHEMA public`,

	`CREATE TABLE IF NOT EXISTS resumes (
		id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
		access_count INTEGER,
		analyze_error VARCHAR(500),
		analyze_status VARCHAR(20),
		content_type VARCHAR(255),
		file_hash VARCHAR(64) NOT NULL,
		file_size BIGINT,
		last_accessed_at TIMESTAMP(6),
		original_filename VARCHAR(255) NOT NULL,
		resume_text TEXT,
		storage_key VARCHAR(500),
		storage_url VARCHAR(1000),
		uploaded_at TIMESTAMP(6) NOT NULL,
		analyze_updated_at TIMESTAMP,
		analyze_recovery_count INTEGER NOT NULL DEFAULT 0,
		analyze_attempt_id VARCHAR(36),
		CONSTRAINT resumes_analyze_status_check
			CHECK (analyze_status IN ('PENDING', 'PROCESSING', 'COMPLETED', 'FAILED')),
		CONSTRAINT idx_resume_hash UNIQUE (file_hash)
	)`,

	`CREATE TABLE IF NOT EXISTS resume_analyses (
		id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
		analyzed_at TIMESTAMP(6) NOT NULL,
		content_score INTEGER,
		expression_score INTEGER,
		overall_score INTEGER,
		project_score INTEGER,
		skill_match_score INTEGER,
		strengths_json TEXT,
		structure_score INTEGER,
		suggestions_json TEXT,
		summary TEXT,
		resume_id BIGINT NOT NULL,
		CONSTRAINT fk_resume_analyses_resume FOREIGN KEY (resume_id) REFERENCES resumes(id)
	)`,

	`CREATE TABLE IF NOT EXISTS llm_global_setting (
		id BIGINT NOT NULL PRIMARY KEY,
		created_at TIMESTAMP(6) NOT NULL,
		default_chat_provider_id VARCHAR(64) NOT NULL,
		default_embedding_provider_id VARCHAR(64) NOT NULL,
		updated_at TIMESTAMP(6) NOT NULL
	)`,

	`CREATE TABLE IF NOT EXISTS llm_provider_config (
		id VARCHAR(64) NOT NULL PRIMARY KEY,
		api_key_ciphertext VARCHAR(4096) NOT NULL,
		api_key_nonce VARCHAR(64) NOT NULL,
		base_url VARCHAR(512) NOT NULL,
		builtin BOOLEAN NOT NULL,
		created_at TIMESTAMP(6) NOT NULL,
		embedding_dimensions INTEGER,
		embedding_model VARCHAR(128),
		enabled BOOLEAN NOT NULL,
		model VARCHAR(128) NOT NULL,
		supports_embedding BOOLEAN NOT NULL,
		temperature DOUBLE PRECISION,
		updated_at TIMESTAMP(6) NOT NULL
	)`,

	// Go 版语音配置单例表（Java 版存储在 YAML；落库以获得同等持久化语义）。
	`CREATE TABLE IF NOT EXISTS voice_config (
		id BIGINT NOT NULL PRIMARY KEY,
		asr_json TEXT NOT NULL,
		tts_json TEXT NOT NULL,
		api_key_nonce VARCHAR(64) NOT NULL DEFAULT '',
		api_key_ciphertext VARCHAR(4096) NOT NULL DEFAULT '',
		updated_at TIMESTAMP NOT NULL
	)`,

	`CREATE INDEX IF NOT EXISTS idx_resume_analyze_status_updated ON resumes (analyze_status, analyze_updated_at)`,
	`CREATE INDEX IF NOT EXISTS idx_resume_analyses_resume ON resume_analyses (resume_id, analyzed_at)`,
	`CREATE INDEX IF NOT EXISTS idx_interview_session_resume_created ON interview_sessions (resume_id, created_at)`,
}

// Run 执行幂等迁移；个别语句失败（如缺权限建扩展）仅告警不阻断。
func Run(ctx context.Context, db *gorm.DB, logger *slog.Logger) error {
	for _, stmt := range statements {
		if err := db.WithContext(ctx).Exec(stmt).Error; err != nil {
			// CREATE EXTENSION 已存在等情况：告警继续。
			logger.Warn("迁移语句执行失败（跳过）", slog.String("error", err.Error()))
		}
	}
	logger.Info("数据库结构检查完成")
	return nil
}

// EnsureVoiceConfigColumns 兼容更早创建的 voice_config 表（补列）。
func EnsureVoiceConfigColumns(ctx context.Context, db *gorm.DB, logger *slog.Logger) error {
	alters := []string{
		`ALTER TABLE voice_config ADD COLUMN IF NOT EXISTS api_key_nonce VARCHAR(64) NOT NULL DEFAULT ''`,
		`ALTER TABLE voice_config ADD COLUMN IF NOT EXISTS api_key_ciphertext VARCHAR(4096) NOT NULL DEFAULT ''`,
	}
	for _, stmt := range alters {
		if err := db.WithContext(ctx).Exec(stmt).Error; err != nil {
			return fmt.Errorf("migration: 补齐 voice_config 列失败: %w", err)
		}
	}
	return nil
}
